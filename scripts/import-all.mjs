#!/usr/bin/env node
/**
 * Rebuilds every generated article and regenerates the registry index.
 *   - content-src/raw/<slug>.txt       scraped breakdowns → scripts/import-problem.mjs
 *   - content-src/authored/<slug>.md   hand-written breakdowns → scripts/build-authored.mjs
 *
 *   node scripts/import-all.mjs [--report]
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const rawDir = path.join(ROOT, "content-src", "raw");
const authoredDir = path.join(ROOT, "content-src", "authored");
const flags = process.argv.slice(2);
const list = (dir, ext) =>
  fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(ext)).map((f) => f.slice(0, -ext.length)) : [];

const raw = list(rawDir, ".txt");
const authored = list(authoredDir, ".md");
const run = (script, args) => execFileSync(process.execPath, [path.join(ROOT, "scripts", script), ...args], { stdio: "inherit" });

for (const slug of raw) run("import-problem.mjs", [path.join(rawDir, `${slug}.txt`), slug, ...flags]);
for (const slug of authored) run("build-authored.mjs", [path.join(authoredDir, `${slug}.md`)]);

const slugs = [...new Set([...raw, ...authored])].sort();
const ident = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, "_$1");
const index =
  `// Generated by scripts/import-all.mjs — do not edit by hand.\n` +
  `import type { Article } from "../types";\n` +
  slugs.map((s) => `import ${ident(s)} from "./${s}.json";`).join("\n") +
  `\n\nexport const importedArticles = [\n${slugs.map((s) => `  ${ident(s)},`).join("\n")}\n] as unknown as Article[];\n`;
fs.writeFileSync(path.join(ROOT, "src", "content", "problems", "index.ts"), index);
// Lightweight list of available slugs for client components (search) — avoids bundling article bodies.
const catalog = slugs.map((slug) => {
  const a = JSON.parse(fs.readFileSync(path.join(ROOT, "src", "content", "problems", `${slug}.json`), "utf8"));
  return { section: a.section, slug };
});
fs.writeFileSync(path.join(ROOT, "src", "content", "problems", "catalog.json"), JSON.stringify(catalog, null, 2) + "\n");
// Every Q&A question, so search can find a question from any page.
const questions = [];
for (const slug of slugs) {
  const a = JSON.parse(fs.readFileSync(path.join(ROOT, "src", "content", "problems", `${slug}.json`), "utf8"));
  if (a.section !== "questions") continue;
  for (const b of a.blocks) if (b.type === "qa") questions.push({ slug, id: b.id, n: b.number, q: b.question.replace(/[*`]/g, "") });
}
questions.sort((x, y) => x.n - y.n);
fs.writeFileSync(path.join(ROOT, "src", "content", "problems", "questions.json"), JSON.stringify(questions) + "\n");
console.log(`\n${raw.length} imported + ${authored.length} authored → src/content/problems/index.ts`);
