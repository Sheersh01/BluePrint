import type { Metadata } from "next";
import { AppShell } from "@/components/shell/AppShell";
import { navigation } from "@/content/navigation";
import { getArticle } from "@/content/registry";
import { buildPracticePlan } from "@/lib/practice/steps";
import { tagsForProblem } from "@/content/tags";
import { PracticeIndex, type PracticeItem } from "@/components/practice/PracticeIndex";

export const metadata: Metadata = {
  title: "Practice",
  description:
    "Mock system design interviews on a whiteboard: answer each step, draw your design, and get feedback as you go.",
};

/** Practice groups, in display order: questions from real interviews first, then the standard set. */
const GROUPS = [
  { section: "real-life", label: "From real interviews" },
  { section: "problem-breakdowns", label: "Standard problems" },
] as const;

export default function PracticeHome() {
  const items: PracticeItem[] = GROUPS.flatMap(({ section, label }) =>
    (navigation.find((s) => s.section === section)?.items ?? []).flatMap((leaf) => {
      const article = getArticle(section, leaf.slug);
      if (!article) return [];
      const steps = buildPracticePlan(article).steps.length;
      const tags = tagsForProblem(leaf.slug, article.tags.map((t) => t.label)).map((t) => t.id);
      return steps ? [{ slug: leaf.slug, title: article.title, difficulty: article.difficulty, steps, group: label, tags }] : [];
    }),
  );

  return (
    <AppShell>
      <div className="mx-auto max-w-[920px] px-5 pt-12 pb-32 sm:px-10">
        <header className="border-b border-line pb-7">
          <p className="label-caps text-primary">Practice</p>
          <h1 className="mt-3 font-serif text-[40px] leading-[1.05] font-medium tracking-[-0.025em] text-ink sm:text-[48px]">
            Run the interview yourself
          </h1>
          <p className="mt-4 max-w-[62ch] text-[16px] leading-relaxed text-body">
            Pick a problem and work through it the way a real interview goes — requirements, core entities, API, a
            high-level design, then deep dives. Sketch on the whiteboard, explain your thinking, and get feedback on each
            step before you move on. Your board and answers are saved in this browser.
          </p>
          <p className="mt-3 max-w-[62ch] text-[13px] leading-relaxed text-muted">
            Feedback is generated by an AI model and compared against each breakdown&apos;s write-up. Treat it as a
            second opinion, not a verdict.
          </p>
        </header>
        <div className="mt-8">
          <PracticeIndex items={items} />
        </div>
      </div>
    </AppShell>
  );
}
